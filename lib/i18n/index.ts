function preserveDisplayCase(source: string, target: string): string {
  const letters = source.replace(/[^A-Za-zÄÖÜÀ-ÿ]/g, "")
  return letters && letters === letters.toLocaleUpperCase("de-CH") ? target.toLocaleUpperCase("en-GB") : target
}

