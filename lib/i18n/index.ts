export function translateUiText(value: unknown, locale: AppLocale): string {
  const raw = value == null ? "" : String(value)
  if (locale === "de" || !raw) return raw

  const leading = raw.match(/^\s*/)?.[0] ?? ""
  const trailing = raw.match(/\s*$/)?.[0] ?? ""
  const source = raw.trim()
  if (!source) return raw

  const exact = ALL_ENGLISH[source]
  if (exact) return `${leading}${preserveDisplayCase(source, exact)}${trailing}`

  const caseInsensitive = ENGLISH_CASE_INSENSITIVE.get(source.toLocaleLowerCase("de-CH"))
  if (caseInsensitive) return `${leading}${preserveDisplayCase(source, caseInsensitive)}${trailing}`

  for (const [pattern, replacer] of DYNAMIC_ENGLISH) {
    const match = source.match(pattern)
    if (match) return `${leading}${preserveDisplayCase(source, replacer(...match))}${trailing}`
  }

  if (source.includes(",")) {
    const items = source.split(",").map((item) => item.trim())
    const translatedItems = items.map((item) => ALL_ENGLISH[item])
    if (translatedItems.every(Boolean)) return `${leading}${translatedItems.join(", ")}${trailing}`
  }
  return raw
}

export function hasEnglishTranslation(value: unknown): boolean {
  const source = value == null ? "" : String(value).trim()
  if (!source) return true
  if (ALL_ENGLISH[source] || ENGLISH_CASE_INSENSITIVE.has(source.toLocaleLowerCase("de-CH"))) return true
  return DYNAMIC_ENGLISH.some(([pattern]) => pattern.test(source))
}
